"""Dispatcher copilot: one `ask()` for both kinds of question.

  "Which jobs are late in Charlotte today, and why?"  -> answered from Postgres (role-scoped),
                                                          each line proven by job + ticket IDs,
                                                          plus what the SOP says to do next.
  "How much credit does a Gold customer get?"         -> answered from the SOP PDFs with citations.
  Anything else                                        -> "I don't know".

Job facts are never generated by the model: they come straight from the database,
so the numbers in an answer always match the dashboard.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta

from backend import queries, rag
from backend.auth import User

CITIES = ["Charlotte", "Raleigh", "Durham", "Greensboro", "Winston-Salem"]
CITY_ALIASES = {"clt": "Charlotte", "gso": "Greensboro", "winston salem": "Winston-Salem"}
JOB_WORDS = re.compile(r"\b(jobs?|deliver(y|ies)|orders?|my (work|day|schedule)|technicians?|drivers?)\b", re.I)
LATE_WORDS = re.compile(r"\b(late|delay(ed|s)?|behind|overdue|breach(ed|es)?|sla|at risk|stuck)\b", re.I)
WHICH_WORDS = re.compile(r"\b(which|what|list|show|how many|any|are there|who)\b", re.I)


@dataclass
class CopilotAnswer:
    text: str
    kind: str                                   # 'jobs' | 'sop' | 'idk'
    rows: list[dict] = field(default_factory=list)
    sop: rag.Answer | None = None

    @property
    def citations(self) -> list[rag.Citation]:
        return self.sop.citations if self.sop else []


def _find_city(q: str) -> str | None:
    low = q.lower()
    for alias, city in CITY_ALIASES.items():
        if re.search(rf"\b{alias}\b", low):
            return city
    for city in CITIES:
        if city.lower() in low or city.lower().replace("-", " ") in low:
            return city
    return None


def _find_day(q: str, today: date) -> date:
    low = q.lower()
    if "yesterday" in low:
        return today - timedelta(days=1)
    if "tomorrow" in low:
        return today + timedelta(days=1)
    if m := re.search(r"\b(\d{4}-\d{2}-\d{2})\b", low):
        return date.fromisoformat(m.group(1))
    return today


# "How often should dispatchers check delayed jobs?" is a procedure question, not a lookup.
PROCEDURE_WORDS = re.compile(
    r"\b(how (do|does|should|to|often|quickly|fast|long|soon|many times)|what should|should (i|we|dispatchers?|technicians?)"
    r"|when (does|do|is|should|must)|count(s)? as|what (are|is) the|deadlines?|policy|procedure|sop|credit|refund|first)\b",
    re.I)
# A lookup is about real jobs at a real time/place: today, yesterday, now, my jobs, a city, a date.
DATA_CUES = re.compile(r"\b(today|yesterday|tomorrow|now|right now|currently|this (morning|afternoon)|my jobs?"
                       r"|of my|\d{4}-\d{2}-\d{2})\b", re.I)


def is_job_question(q: str) -> bool:
    if not LATE_WORDS.search(q) or PROCEDURE_WORDS.search(q):
        return False
    return bool(DATA_CUES.search(q) or _find_city(q)) and bool(JOB_WORDS.search(q) or WHICH_WORDS.search(q))


def _fmt_late(m: int) -> str:
    return f"{m // 60}h {m % 60:02d}m" if m >= 60 else f"{m}m"


def answer_jobs(conn, user: User, question: str, as_of: datetime) -> CopilotAnswer:
    day = _find_day(question, as_of.date())
    city = _find_city(question)
    breach_only = bool(re.search(r"\b(breach(ed|es)?|sla)\b", question, re.I))
    tier = next((t for t in ("Gold", "Silver", "Bronze") if re.search(rf"\b{t}\b", question, re.I)), None)
    rows = queries.jobs_for_day(conn, user, day, as_of, city=city)
    if tier:
        rows = [r for r in rows if r["tier"] == tier]
    late = [r for r in rows if (r["is_breach"] if breach_only else r["is_delayed"])]
    late.sort(key=lambda r: (r["tier"] != "Gold", not r["is_breach"], r["priority"] != "High", -r["minutes_late"]))

    where = (f" for {tier} customers" if tier else "") + (f" in {city}" if city else "")
    whose = "" if user.is_manager else " assigned to you"
    when = "today" if day == as_of.date() else f"on {day:%b %d}"
    what = "in SLA breach" if breach_only else "late"
    if not late:
        return CopilotAnswer(f"No jobs{whose}{where} are {what} {when} (checked {len(rows)} jobs, as of {as_of:%H:%M}).",
                             "jobs", [])

    lines = [f"**{len(late)} of {len(rows)} jobs{whose}{where} are {what} {when}** (as of {as_of:%H:%M}):", ""]
    for r in late:
        why = (f"{r['reason']} — “{r['reason_note']}” (ticket {r['reason_ticket']})"
               if r["reason"] else "no reason logged — no service ticket on this job")
        state = "SLA breached" if r["is_breach"] else "SLA not yet breached"
        lines.append(f"- **{r['job_id']}** · {r['customer']} ({r['tier']}) · {r['technician']} · "
                     f"{_fmt_late(r['minutes_late'])} late, {state}, status {r['status']}. Why: {why}")
    reasons = {r["reason"] for r in late if r["reason"]}
    no_reason = sum(1 for r in late if not r["reason"])
    lines += ["", f"Most common reason: **{max(reasons, key=lambda x: sum(r['reason'] == x for r in late))}**." if reasons else ""]
    if no_reason:
        lines.append(f"{no_reason} job(s) have no ticket explaining the delay — ask the technician to log one.")

    sop = rag.ask_sop("what actions to take for delayed jobs by reason traffic weather breakdown parts")
    return CopilotAnswer("\n".join(l for l in lines if l is not None), "jobs", late, sop)


def ask(conn, user: User, question: str, as_of: datetime | None = None, client=None) -> CopilotAnswer:
    as_of = as_of or datetime.now().replace(second=0, microsecond=0)
    q = question.strip()
    if not q:
        return CopilotAnswer(rag.IDK, "idk")
    if is_job_question(q):
        return answer_jobs(conn, user, q, as_of)
    sop = rag.ask_sop(q, client=client)
    if sop.is_idk:
        return CopilotAnswer(rag.IDK, "idk", sop=sop)
    return CopilotAnswer(sop.text, "sop", sop=sop)
